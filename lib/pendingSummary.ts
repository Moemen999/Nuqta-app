/**
 * سطر "مستنيين ردك" في الرئيسية — كروت "نزل؟" و"اتخصم؟" و"اتدفع؟"/"استلمت؟"
 * اتلمّت في شيت بيفتحه السطر ده بدل ما كل كارت ياخد حتة من الرئيسية
 * (2026-09-29). الصيغ متحددة بالنص من مؤمن، فمتتغيّرش من غير قرار.
 *
 * صفر ← `null`: السطر مبيتعرضش خالص، مش "مفيش حاجة مستنية".
 */
export function pendingSummaryPhrase(n: number): string | null {
  if (!Number.isInteger(n) || n <= 0) return null;
  if (n === 1) return 'عندك حاجة مستنية ردك';
  if (n === 2) return 'عندك حاجتين مستنيين ردك';
  if (n <= 10) return `عندك ${n} حاجات مستنيين ردك`;
  return `عندك ${n} حاجة مستنيين ردك`;
}
