/**
 * رسالة "الكتابة ما وصلتش للسيرفر".
 *
 * ليه منفصلة وليه فيها اسم السجل: الكتابة في فايربيز مبتستناش تأكيد السيرفر
 * (قاعدة 7)، فالمودال بيقفل قبل ما الرفض يوصل أصلاً. يعني رسالة خطأ جوه
 * الفورم **مستحيلة** للحالة دي — الفورم مابقاش موجود. التنبيه العام هو
 * المكان الوحيد الممكن، وعشان كده لازم يقول **إيه** اللي فشل، مش "فيه
 * تعديل" وبس. المستخدم عنده اشتراكين وتلات ديون — "فيه تعديل ما اتحفظش"
 * مبتقولّهوش يراجع إيه.
 */
export const WRITE_ERROR_TITLE = 'فيه تعديل ما اتحفظش';

/**
 * بعد القد ده القفل بتاع "تنبيه واحد في المرة" بيتفك لوحده.
 *
 * التنبيه بيتقفل عادةً بزرار "تمام". بس لو المنصة بلعت التنبيه (تنبيه تاني
 * كان مفتوح)، الزرار عمره ما هيتضغط — والقفل كان هيفضل مقفول لآخر الجلسة،
 * فكل كتابة تفشل بعدها تبقى صامتة.
 */
export const WRITE_ERROR_RESET_MS = 10000;
const TAIL = 'راجع البيانات وجرب من الأول.';

export function writeErrorBody(label?: string) {
  if (!label) return `التعديل ما وصلش للسيرفر واترجع تاني. ${TAIL}`;
  return `التعديل ده ما وصلش للسيرفر واترجع تاني: ${label}. ${TAIL}`;
}

/** «الاشتراك "نتفليكس"» — الاقتباس بيفصل اسم المستخدم عن كلامنا */
export function namedLabel(kind: string, name?: string) {
  const clean = (name || '').trim();
  return clean ? `${kind} "${clean}"` : kind;
}
