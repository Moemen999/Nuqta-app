/**
 * سطر «حاجات محتاجة انتباهك» في الرئيسية (2026-11-13، قرار مؤمن): التنبيهات الروتينية
 * (الإيميل، لسه ما سجلتش، رصيد قرب يخلص، ميزانية فئة، اشتراك وقسط جمعية جايين)
 * اتلمّت في سطر واحد بيفتح شيت، بدل ما كل واحد ياخد بانر لوحده. الصيغ على نمط
 * `pendingSummaryPhrase` (`lib/pendingSummary.ts`) — متحددة بالنص، فمتتغيّرش من غير قرار.
 *
 * صفر ← `null`: السطر مبيتعرضش خالص.
 */
export function attentionSummaryPhrase(n: number): string | null {
  if (!Number.isInteger(n) || n <= 0) return null;
  if (n === 1) return 'عندك حاجة محتاجة انتباهك';
  if (n === 2) return 'عندك حاجتين محتاجين انتباهك';
  if (n <= 10) return `عندك ${n} حاجات محتاجة انتباهك`;
  return `عندك ${n} حاجة محتاجة انتباهك`;
}

